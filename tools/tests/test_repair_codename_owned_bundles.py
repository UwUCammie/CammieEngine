    def test_runtime_lock_blocks_apply(self):
        result = self.plan()
        with (self.locks / 'runtime-1.lock').open('a+') as lock:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
            with self.assertRaises(BlockingIOError):
                repair.apply_plan(result, self.plan_path)
        self.assertFalse((self.runtime / self.owner).exists())

    def test_mid_apply_failure_rolls_back_only_created_files(self):
        target = self.runtime / self.owner / 'songs/song/scripts/script.hx'
        target.parent.mkdir(parents=True)
        target.write_text('// preserved', newline='\n')
        result = self.plan()
        real_link = repair.os.link
        count = 0
        def fail_second(source, dest):
            nonlocal count
            count += 1
            if count == 2:
                raise OSError('simulated link failure')
            return real_link(source, dest)
        with patch.object(repair.os, 'link', side_effect=fail_second):
            with self.assertRaisesRegex(OSError, 'simulated link failure'):
                repair.apply_plan(result, self.plan_path)
        self.assertEqual(target.read_text(), '// preserved')
        for row in result['candidates']:
            self.assertFalse(Path(row['target']).exists())
        self.assertEqual(len(list((self.work / 'import-refresh-backups').glob('*/rolled-back.json'))), 1)

