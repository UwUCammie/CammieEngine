        rows = json.loads((receipt / 'replacements.json').read_text())
        self.assertEqual(len(rows), 4)
        for row in result['replacements']:
            backup = receipt / 'backups' / Path(row['target']).relative_to(self.runtime)
            self.assertEqual(repair.digest(backup), row['beforeSha256'])
            self.assertEqual(repair.digest(Path(row['target'])), row['afterSha256'])
        dependency = self.runtime / self.owner / 'compat-engine-base/character-dependency.json'
        self.assertEqual(dependency.read_text(), json.dumps(
            {'version': 2, 'ownerNamespace': self.owner, 'fallbackId': 'bf',
             'sprite': 'bf', 'files': []}, separators=(',', ':')))

