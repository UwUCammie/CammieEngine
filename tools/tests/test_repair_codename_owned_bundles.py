        result = repair.make_plan(self.donor, self.runtime, self.preview, self.owner,
                                  allow_generated_replacements=True)
        kinds = {row['kind'] for row in result['replacements']}
        self.assertEqual(kinds, {
            'codename-stage-converter-script', 'codename-camera-sidecar-schema',
            'codename-song-metadata-schema', 'codename-character-atlas-registry',
        })
        self.assertEqual(len(result['replacements']), 4)
