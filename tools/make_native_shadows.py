#!/usr/bin/env python3
"""Generate source-native/: hxcpp standard library classes with the multiplayer hooks.

Each file is the portable Haxe toolchain's own std/cpp/_std implementation with a few
lines added, so a toolchain update is picked up by running this again:

- Type.resolveClass / resolveEnum ask multiplayer.ScriptSandbox before returning;
- sys.FileSystem and sys.io.File read through multiplayer.MpOverlay and refuse writes the
  sandbox does not allow;
- sys.io.Process refuses to start while the sandbox is active.

source-native is a classpath only for native (cpp) builds (Project.xml), so the
interpreter-based tests keep the plain standard library.
"""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
STD = ROOT / ".tools/haxe/std/cpp/_std"
OUT = ROOT / "source-native"
NOTE = "// Generated by tools/make_native_shadows.py from the toolchain's std/cpp/_std; do not edit.\n"


def patch(text, pairs, name):
    for old, new in pairs:
        if text.count(old) != 1:
            raise SystemExit(f"{name}: anchor not found exactly once: {old!r}")
        text = text.replace(old, new)
    return NOTE + text


def main():
    files = {
        "Type.hx": [
            ("\t\t\tvar result:Class<Dynamic> = Class.Resolve(name);\n\t\t\tif (result != null && result.__IsEnum())",
             "\t\t\tif (!multiplayer.ScriptSandbox.classAllowed(name))\n\t\t\t\treturn null;\n"
             "\t\t\tvar result:Class<Dynamic> = Class.Resolve(name);\n\t\t\tif (result != null && result.__IsEnum())"),
            ("\t\t\tvar result:Class<Dynamic> = Class.Resolve(name);\n\t\t\tif (result != null && !result.__IsEnum())",
             "\t\t\tif (!multiplayer.ScriptSandbox.classAllowed(name))\n\t\t\t\treturn null;\n"
             "\t\t\tvar result:Class<Dynamic> = Class.Resolve(name);\n\t\t\tif (result != null && !result.__IsEnum())"),
        ],
        "sys/FileSystem.hx": [
            ("\tpublic static function exists(path:String):Bool {\n\t\treturn NativeSys.sys_exists(makeCompatiblePath(path));",
             "\tpublic static function exists(path:String):Bool {\n\t\tif (multiplayer.MpOverlay.provides(path))\n\t\t\treturn true;\n"
             "\t\treturn NativeSys.sys_exists(makeCompatiblePath(multiplayer.MpOverlay.read(path)));"),
            ("\tpublic static function rename(path:String, newPath:String):Void {\n",
             "\tpublic static function rename(path:String, newPath:String):Void {\n"
             "\t\tmultiplayer.ScriptSandbox.guardWrite(path);\n\t\tmultiplayer.ScriptSandbox.guardWrite(newPath);\n"),
            ("\t\tvar s:FileStat = NativeSys.sys_stat(makeCompatiblePath(path));",
             "\t\tvar s:FileStat = NativeSys.sys_stat(makeCompatiblePath(multiplayer.MpOverlay.isFolder(path) ? Sys.getCwd() : multiplayer.MpOverlay.read(path)));"),
            ("\tpublic static function isDirectory(path:String):Bool {\n\t\treturn kind(path) == \"dir\";",
             "\tpublic static function isDirectory(path:String):Bool {\n\t\tif (multiplayer.MpOverlay.isFolder(path))\n\t\t\treturn true;\n"
             "\t\treturn kind(path) == \"dir\";"),
            ("\tpublic static function createDirectory(path:String):Void {\n",
             "\tpublic static function createDirectory(path:String):Void {\n\t\tmultiplayer.ScriptSandbox.guardWrite(path);\n"),
            ("\tpublic static function deleteFile(path:String):Void {\n",
             "\tpublic static function deleteFile(path:String):Void {\n\t\tmultiplayer.ScriptSandbox.guardWrite(path);\n"),
            ("\tpublic static function deleteDirectory(path:String):Void {\n",
             "\tpublic static function deleteDirectory(path:String):Void {\n\t\tmultiplayer.ScriptSandbox.guardWrite(path);\n"),
            ("\tpublic static function readDirectory(path:String):Array<String> {\n\t\treturn NativeSys.sys_read_dir(path);",
             "\tpublic static function readDirectory(path:String):Array<String> {\n"
             "\t\tif (!multiplayer.MpOverlay.isFolder(path))\n\t\t\treturn NativeSys.sys_read_dir(path);\n"
             "\t\tvar real:Array<String> = null;\n"
             "\t\tif (kind(path) == \"dir\")\n\t\t\treal = NativeSys.sys_read_dir(path);\n"
             "\t\treturn multiplayer.MpOverlay.children(path, real);"),
        ],
        "sys/io/File.hx": [
            ("\t\treturn NativeFile.file_contents_string(path);",
             "\t\treturn NativeFile.file_contents_string(multiplayer.MpOverlay.read(path));"),
            ("\t\tvar data = NativeFile.file_contents_bytes(path);",
             "\t\tvar data = NativeFile.file_contents_bytes(multiplayer.MpOverlay.read(path));"),
            ("\t\treturn untyped new FileInput(NativeFile.file_open(path, (if (binary) \"rb\" else \"r\")));",
             "\t\treturn untyped new FileInput(NativeFile.file_open(multiplayer.MpOverlay.read(path), (if (binary) \"rb\" else \"r\")));"),
            ("\tpublic static function write(path:String, binary:Bool = true):FileOutput {\n",
             "\tpublic static function write(path:String, binary:Bool = true):FileOutput {\n\t\tmultiplayer.ScriptSandbox.guardWrite(path);\n"),
            ("\tpublic static function append(path:String, binary:Bool = true):FileOutput {\n",
             "\tpublic static function append(path:String, binary:Bool = true):FileOutput {\n\t\tmultiplayer.ScriptSandbox.guardWrite(path);\n"),
            ("\tpublic static function update(path:String, binary:Bool = true):FileOutput {\n",
             "\tpublic static function update(path:String, binary:Bool = true):FileOutput {\n\t\tmultiplayer.ScriptSandbox.guardWrite(path);\n"),
        ],
        "sys/io/Process.hx": [
            ("\tpublic function new(cmd:String, ?args:Array<String>, ?detached:Bool):Void {\n",
             "\tpublic function new(cmd:String, ?args:Array<String>, ?detached:Bool):Void {\n\t\tmultiplayer.ScriptSandbox.guardProcess(cmd);\n"),
        ],
    }
    for name, pairs in files.items():
        source = (STD / name).read_text(encoding="utf-8")
        # Macros run on the eval target, which needs its own unmodified class.
        fallback = STD.parents[1] / "eval/_std" / name
        if not fallback.is_file():
            fallback = STD.parents[1] / name
        target = OUT / name
        target.parent.mkdir(parents=True, exist_ok=True)
        text = (NOTE + "#if (cpp && !macro)\n" + patch(source, pairs, name)[len(NOTE):]
                + "\n#else\n" + fallback.read_text(encoding="utf-8") + "\n#end\n")
        target.write_text(text, encoding="utf-8", newline="\n")
        print("wrote", target.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
